import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {MeshguardWasm} from '../../web/meshguard.mjs';
if(!process.env.MESHGUARD_NATIVE_LIBRARY)throw new Error('Set MESHGUARD_NATIVE_LIBRARY to an independently built native FFI library');
const core=new MeshguardWasm((await WebAssembly.instantiate(readFileSync('zig-out/bin/meshguard.wasm'),{})).instance);
const a=core.createIdentity(new Uint8Array(32).fill(1)),b=core.createIdentity(new Uint8Array(32).fill(2));
const peer=i=>({publicKey:i.publicKey(),wgPublicKey:i.wgPublicKey()});
const hex=b=>Buffer.from(b).toString('hex');
const payloads=[new Uint8Array(),new TextEncoder().encode('WASM ↔ native — Olá 🌎'),new Uint8Array(1024).fill(17)];
const request={public:hex(a.publicKey()),wgPublic:hex(a.wgPublicKey()),nativePublic:hex(b.publicKey()),samples:payloads.map(plaintext=>({plaintext:hex(plaintext),packet:hex(a.seal(peer(b),plaintext))}))};
const result=spawnSync('python3',['tests/wasm/native_ffi_interop.py',process.env.MESHGUARD_NATIVE_LIBRARY],{input:JSON.stringify(request),encoding:'utf8',timeout:45000});
if(result.status!==0)throw new Error(result.stderr||'Native interoperability harness failed');
const reply=JSON.parse(result.stdout);
assert.equal(reply.nativeReceived,payloads.length);
reply.nativePackets.forEach((packet,i)=>assert.deepEqual(a.open(peer(b),Buffer.from(packet,'hex')),payloads[i]));
a.destroy();b.destroy();
console.log(JSON.stringify({result:'PASS',wasmToNative:3,nativeToWasm:3,transport:'real loopback UDP + native FFI',payloads:['empty','UTF-8','1024 bytes']}));
